import {test} from 'node:test';
import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,dirname,resolve,basename} from 'node:path';
import {startDatabaseServer} from '../server/sqlite.mjs';
import {startShareGateway} from '../server/share-gateway.mjs';

const bundle=await build({stdin:{contents:`export {initialData} from './src/data';export {migrate,validate} from './src/store';export {post,reverse} from './src/finance';`,resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'esm'});
const {initialData,migrate,post,reverse,validate}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const secret='isolated-test-identity';
const ownerEmail='owner@example.com';
const origin='https://test.ngrok.app';
const signed=email=>({'x-khaneh-gateway-key':secret,'x-khaneh-google-email':email});

for(let round=1;round<=3;round++)test(`shared persistence, access, conflicts and restart round ${round}`,async()=>{
 const directory=await mkdtemp(join(tmpdir(),'khaneh-sync-'));
 const filename=join(directory,'test.sqlite');
 let server=await startDatabaseServer({filename,port:0,publicOrigin:origin,identitySecret:secret,ownerEmail});
 let gateway;
 let base=()=>`http://127.0.0.1:${server.address().port}`;
 const request=async(url,body,headers={})=>{const response=await fetch(url,{method:'POST',headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(body)});return {...await response.json(),status:response.status}};
 const direct=(path,body)=>request(base()+'/api/database'+path,body);
 try{
  assert.equal((await request(base()+'/api/database/local-session',{}, {Origin:'https://evil.example'})).status,403);
  assert.equal((await request(base()+'/api/database/local-session',{}, {Origin:'http://localhost:4173'})).data,null);
  const data=migrate(structuredClone(initialData),'2026-10-17T10:00:00Z');
  const owner=data.settings.members?.find(m=>m.role==='owner')?.id??'مرزیه';
  const invitation=await direct('/invitations',{data,viewer:owner,revision:0});assert.equal(invitation.status,201);
  const joinRequest=await direct('/invitations/join',{token:invitation.token,name:'محمدامین',email:'member@example.com'});assert.equal(joinRequest.status,202);
  assert.equal((await direct('/sync',{action:'read',token:joinRequest.token})).status,403);
  const decision=await direct('/access/decide',{ownerKey:invitation.ownerKey,token:joinRequest.token,approved:true});assert.ok(decision.member.id);
  gateway=await startShareGateway({port:0,databasePort:server.address().port,publicOrigin:origin,identitySecret:secret});
  const sync=(body,headers={})=>request(`http://127.0.0.1:${gateway.address().port}/api/database/sync`,body,headers);
  const credentials={token:joinRequest.token};
  const localOwner=await request(base()+'/api/database/local-session',{}, {Origin:'http://localhost:4173'});
  assert.equal(localOwner.status,200);assert.equal(localOwner.member.role,'owner');
  assert.equal((await direct('/sync',{action:'read',ownerKey:localOwner.ownerKey})).status,200);
  assert.equal((await request(`http://127.0.0.1:${gateway.address().port}/api/database/local-session`,{},signed(ownerEmail))).status,403);
  assert.equal((await sync({action:'read',viewer:owner})).status,403);
  assert.equal((await sync({action:'read'},{'x-khaneh-google-email':ownerEmail})).status,403);
  assert.equal((await sync({action:'read'},signed('unknown@example.com'))).status,403);
  assert.equal((await sync({action:'read'}, {...signed(ownerEmail),Origin:'https://evil.example'})).status,403);
  let snapshot=await sync({action:'read',...credentials});assert.equal(snapshot.status,200);
  assert.equal((await sync({action:'invite',...credentials})).status,403);
  assert.equal((await sync({action:'invite'},signed(ownerEmail))).status,201);
  assert.ok(Array.isArray((await sync({action:'requests'},signed(ownerEmail))).requests));
  const original=structuredClone(snapshot.data);
  const account=original.accounts.find(a=>a.visibility==='shared');assert.ok(account);
  const tx={id:`round-${round}`,title:'تست ثبت مشترک',amount:100,type:'expense',category:'خوراک',accountId:account.id,date:'2026-10-17',createdBy:decision.member.id,visibility:'shared'};
  const candidate=post(original,tx);validate(candidate);
  const write={action:'write',expected:original,data:candidate,...credentials};
  const saved=await sync(write);assert.equal(saved.status,200);
  const duplicate=await sync(write);assert.equal(duplicate.status,200);assert.equal(duplicate.revision,saved.revision);
  snapshot=await sync({action:'read'},signed(ownerEmail));assert.deepEqual(snapshot.data,candidate);
  assert.equal(snapshot.data.transactions.filter(t=>t.id===tx.id).length,1);
  const stale=structuredClone(original);stale.settings.name='stale device';
  assert.equal((await sync({action:'write',data:stale,expected:original,...credentials})).status,409);
  const escalation=structuredClone(candidate);escalation.settings.members.find(m=>m.id===decision.member.id).role='owner';escalation.settings.members.find(m=>m.id===owner).role='editor';
  assert.equal((await sync({action:'write',expected:candidate,data:escalation,...credentials})).status,403);
  const invalid=structuredClone(candidate);invalid.accounts[0].balance++;
  assert.equal((await sync({action:'write',expected:candidate,data:invalid,...credentials})).status,400);
  const reader=structuredClone(candidate);reader.settings.members.find(m=>m.id===decision.member.id).role='reader';
  assert.equal((await sync({action:'write',expected:candidate,data:reader},signed(ownerEmail))).status,200);
  const forbidden=structuredClone(reader);forbidden.settings.name='reader edit';
  assert.equal((await sync({action:'write',expected:reader,data:forbidden,...credentials})).status,403);
  const ownProfile=structuredClone(reader);ownProfile.settings.members.find(m=>m.id===decision.member.id).name='نام تازه';
  assert.equal((await sync({action:'write',expected:reader,data:ownProfile,...credentials})).status,200);
  const reversed=reverse(ownProfile,tx.id);validate(reversed);
  assert.equal((await sync({action:'write',expected:ownProfile,data:reversed},signed(ownerEmail))).status,200);
  assert.equal(reversed.accounts.find(a=>a.id===account.id).balance,original.accounts.find(a=>a.id===account.id).balance);
  const removed=structuredClone(reversed);removed.settings.members.find(m=>m.id===decision.member.id).removed=true;
  assert.equal((await sync({action:'write',expected:reversed,data:removed},signed(ownerEmail))).status,200);
  assert.equal((await sync({action:'read',...credentials})).status,403);
  assert.equal((await sync({action:'read'},signed('member@example.com'))).status,403);
  await new Promise(r=>gateway.close(r));gateway=null;
  await new Promise(r=>server.close(r));
  server=await startDatabaseServer({filename,port:0,identitySecret:secret,ownerEmail});
  const restored=await direct('/sync',{action:'read',ownerKey:invitation.ownerKey});
  assert.deepEqual(restored.data,removed);validate(restored.data);
 }finally{
  if(gateway)await new Promise(r=>gateway.close(r));
  await new Promise(r=>server.close(r));
  assert.equal(dirname(resolve(directory)),resolve(tmpdir()));assert.ok(basename(directory).startsWith('khaneh-sync-'));
  await rm(directory,{recursive:true,force:true});
 }
});

